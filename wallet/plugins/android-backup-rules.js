// Android Auto Backup rules for the wallet.
//
// expo-secure-store's own rules INCLUDE shared preferences and exclude its
// keystore-backed file. On Android an include list means "only these", so the
// app's files were never backed up, and the encrypted profile backup the wallet
// writes to its files directory (privasys-wallet-backup.json, see
// src/services/profile-backup.ts) would not reach the holder's Google account.
//
// These rules keep secure-store's behaviour and add that one file, and nothing
// else: the file is ciphertext under a key only a phrase recovery restores.
// expo-secure-store is configured with configureAndroidBackup: false so the two
// plugins do not fight over the manifest attributes.

const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');

const BACKUP_FILE = 'privasys-wallet-backup.json';

const RULES = `
    <include domain="sharedpref" path="."/>
    <exclude domain="sharedpref" path="SecureStore"/>
    <include domain="file" path="${BACKUP_FILE}"/>`;

const FULL_BACKUP = `<?xml version="1.0" encoding="utf-8"?>
<!-- Auto Backup, Android 11 and lower. Generated by plugins/android-backup-rules.js. -->
<full-backup-content>${RULES}
</full-backup-content>
`;

const EXTRACTION = `<?xml version="1.0" encoding="utf-8"?>
<!-- Auto Backup, Android 12 and higher. Generated by plugins/android-backup-rules.js. -->
<data-extraction-rules>
  <cloud-backup>${RULES}
  </cloud-backup>
  <device-transfer>${RULES}
  </device-transfer>
</data-extraction-rules>
`;

module.exports = function withPrivasysBackupRules(config) {
    config = withAndroidManifest(config, (cfg) => {
        const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
        app.$['android:allowBackup'] = 'true';
        app.$['android:fullBackupContent'] = '@xml/privasys_backup_rules';
        app.$['android:dataExtractionRules'] = '@xml/privasys_data_extraction_rules';
        return cfg;
    });
    return withDangerousMod(config, [
        'android',
        (cfg) => {
            const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
            fs.mkdirSync(dir, { recursive: true });
            fs.writeFileSync(path.join(dir, 'privasys_backup_rules.xml'), FULL_BACKUP);
            fs.writeFileSync(path.join(dir, 'privasys_data_extraction_rules.xml'), EXTRACTION);
            return cfg;
        },
    ]);
};
